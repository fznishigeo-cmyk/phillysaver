const assert = require('node:assert/strict');
const {setup, deal, turn} = require('./search_more_logic.cjs');
(async () => {
  const s = setup();
  s.ctx.state.deals = Array.from({length:70}, (_, i) => deal(i + 1));
  await s.query('mouse'); await turn();
  const top = s.elements['search-amazon-result'];
  assert(!top.hidden && top.innerHTML.includes('class="getdeal"'), 'top CTA exists before loading all 70 matches');
  assert(!s.elements['search-more'], 'related pages still wait for all local matches');
  assert(top.innerHTML.includes('tag=example-20'));
  assert(top.innerHTML.includes('rel="sponsored nofollow noopener"'));
  assert(!s.elements.content.innerHTML.includes('id="search-result-top"'), 'one top CTA on search results');
  s.ctx.showMore(); await turn(); await turn();
  assert(s.elements['search-more']);
  assert(s.elements['search-more'].innerHTML.includes('More on Amazon'));
  assert(!s.elements['search-more'].innerHTML.includes('class="getdeal"'));
  s.ctx.render(); await turn(); await turn();
  assert(!s.elements['search-amazon-result'].hidden && !s.elements.content.innerHTML.includes('id="search-result-top"'));
  await s.query('');
  assert(s.elements['search-amazon-result'].hidden, 'clearing search removes the CTA');
  s.elements.q.value = 'mouse';
  const pending = s.ctx.analyzeSubmit(); await turn(); await s.advance(900); await pending; await turn();
  html = s.elements.content.innerHTML;
  assert(html.includes('<h2>Search results</h2><p id="search-result-top"'));
  assert(html.indexOf('id="search-result-top"') < html.indexOf('Your verified deal'));
  assert.equal((html.match(/id="search-result-top"/g) || []).length, 1);
  assert(s.elements['search-amazon-result'].hidden, 'Analyze shows one top CTA');
  s.elements.q.value = 'https://target.com/product';
  const invalid = s.ctx.analyzeSubmit(); await turn(); await s.advance(900); await invalid;
  html = s.elements.content.innerHTML;
  assert(html.includes('</h2><p id="search-result-top"'));
  assert(html.indexOf('id="search-result-top"') < html.indexOf('Type a product name'));
  console.log('Search box logic passed: early top CTA, one button, small footer, rerender and Analyze');
})().catch(error => {console.error(error); process.exitCode = 1;});
